import type { ArtifactSelection, ByteSize } from "../types.js";

/** What the wizard decided, after prompts or flags. */
export interface WizardAnswers {
  preset: string;
  maxPartBytes: ByteSize;
  largeFileBytes: ByteSize;
  include: string[];
  excludePatterns: string[];
  artifacts: Required<ArtifactSelection>;
  includeSensitiveFiles: boolean;
  outDir: string;
}

export const DEFAULT_ANSWERS: WizardAnswers = {
  preset: "generic",
  maxPartBytes: "300k",
  largeFileBytes: "200k",
  include: [],
  excludePatterns: [],
  artifacts: {
    readme: true,
    manifest: true,
    parts: true,
    navigation: true,
    projectTree: true,
    audit: true,
    monolith: false,
  },
  includeSensitiveFiles: false,
  outDir: "snapshot",
};

function list(values: string[]): string {
  if (values.length === 0) return "[]";
  return `[${values.map((value) => JSON.stringify(value)).join(", ")}]`;
}

function size(value: ByteSize): string {
  return typeof value === "string" ? JSON.stringify(value) : String(value);
}

const PRESET_NAMES = [
  "nextjs · react-vite · vue-vite · nuxt · sveltekit · angular · astro",
  "remix · solid · nest · node-express · node-lib",
  "python-django · python-fastapi · python-lib · go · rust",
  "java-spring · dotnet · php-laravel · ruby-rails",
  "monorepo · docs · infra · generic",
];

/**
 * Opening lines shared by every generated config.
 *
 * The object is plain — no `defineConfig` import — because `codebase-snapshot init` is usually
 * run through `npx`, where the package is *not* installed in the project. An
 * import of `@ankurhalder/codebase-snapshot` therefore made the generated file
 * unloadable by the very next `codebase-snapshot generate`.
 */
const CONFIG_HEADER = `// Generated by codebase-snapshot. A plain object on purpose: this file must load
// even when the package itself is only run through npx.
`;
/**
 * Renders the full, self-documenting config — the only shape `init` writes.
 *
 * Every setting appears at its current value, commented and grouped, because
 * most developers never open the documentation — a file that lists only their
 * changes cannot tell them what else exists. Deleting any line is safe: the
 * defaults are real.
 *
 * There used to be a `--minimal` variant that wrote only the settings that
 * differed from the defaults. It produced a seven-line file for a Next.js
 * project — `export default { preset: "nextjs" }` — which is the one file the
 * user is supposed to open to change things, holding none of the things. The
 * flag is gone: one canonical config, always complete.
 *
 * The object is assigned to `config` and exported by name. An anonymous
 * `export default { … }` is what every lint preset derived from
 * `eslint-config-next` reports as `import/no-anonymous-default-export`, so the
 * generated file was a lint error on the first save in a Next.js project — the
 * preset this tool detects most often.
 */
export function renderConfig(answers: WizardAnswers): string {
  const { artifacts } = answers;

  return `${CONFIG_HEADER}const config = {
  // ── Project ────────────────────────────────────────────────────────────
  // Which project shape to use. Detected from the repo when omitted.
  // ${PRESET_NAMES.join("\n  // ")}
  preset: ${JSON.stringify(answers.preset)},

  // Recorded in the manifest when git cannot report a branch.
  branch: "main",

  // ── Output ─────────────────────────────────────────────────────────────
  // Where the snapshot is written.
  outDir: ${JSON.stringify(answers.outDir)},
  // Scratch directory; the new snapshot is renamed into place atomically.
  tmpDir: "snapshot.tmp",

  // ── Size ───────────────────────────────────────────────────────────────
  // Hard ceiling per part. "300k", 307200 and "1.5mb" are all accepted.
  maxPartBytes: ${size(answers.maxPartBytes)},
  // Files above this size get a head/tail preview instead of the full body.
  largeFileBytes: ${size(answers.largeFileBytes)},
  previewHeadLines: 80,
  previewTailLines: 40,
  // Different ceilings per layer. Unlisted layers use \`default\`.
  budgets: {
    default: ${size(answers.maxPartBytes)},
    byLayer: {},
  },

  // ── What goes in ───────────────────────────────────────────────────────
  // Allow-list. Empty means "everything that is not ignored".
  // Example: ["src/**", "packages/*/src/**"]
  include: ${list(answers.include)},
  // Globs or path segments to drop. Example: ["**/*.test.ts", "docs"]
  excludePatterns: ${list(answers.excludePatterns)},
  // How candidate files are found: "auto" lists them through git when git can
  // and walks the tree otherwise; "git" and "walk" force one path, and "walk" is
  // the escape hatch when .git exists but git cannot list it.
  discovery: "auto",

  // ── Classification ─────────────────────────────────────────────────────
  // "merge" = the preset's rules plus yours (yours win). "replace" = yours only.
  layersMode: "merge",
  // [{ name: "billing", match: "src/features/billing/**" }]
  layers: [],
  // [{ kind: "route", match: "src/app/api/**" }]
  kinds: [],

  // ── Safety ─────────────────────────────────────────────────────────────
  // .env, *.pem, .npmrc, .ssh/ and friends are skipped unless this is true.
  includeSensitiveFiles: ${answers.includeSensitiveFiles},
  secrets: {
    // [{ rule: "internal-token", pattern: /CORP-[A-Z0-9]{32}/ }]
    customPatterns: [],
    // Set true to drop the built-in rules above and keep only customPatterns.
    disableDefaultPatterns: false,
  },

  // ── Artifacts ──────────────────────────────────────────────────────────
  artifacts: {
    readme: ${artifacts.readme},        // README.md
    manifest: ${artifacts.manifest},      // manifest.json — required by validate and report
    parts: ${artifacts.parts},         // parts/part-XXX.md
    navigation: ${artifacts.navigation},    // reports/navigation.md
    projectTree: ${artifacts.projectTree},   // reports/project-tree.md
    audit: ${artifacts.audit},         // reports/audit.md
    monolith: ${artifacts.monolith},     // full-codebase.json + .md (roughly doubles output)
  },
  // Skip the monolith above this size. null = no limit.
  maxMonolithBytes: null,
  // Top-level switch for the monolith, equivalent to artifacts.monolith.
  // When both are present the artifact entry wins; this one exists so the
  // generated file lists every setting the tool accepts.
  includeMonolith: ${artifacts.monolith},

  // ── Advanced ───────────────────────────────────────────────────────────
  // afterGenerate: (manifest) => { /* write your own artifact */ }
  hooks: {},
};

// Exported through a name, not inline: an anonymous default export is reported by
// \`import/no-anonymous-default-export\`, which \`eslint-config-next\` turns on by default, so the
// inline form arrived as a lint warning in exactly the projects this preset targets.
export default config;
`;
}
